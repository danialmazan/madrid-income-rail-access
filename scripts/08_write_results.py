#!/usr/bin/env python3
"""Write a short, reproducible reading of the published descriptive summaries."""
import csv
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
analysis = json.loads((root / 'frontend/public/data/analysis.json').read_text())
with (root / 'validation/generated/sensitivity_summary.csv').open(newline='') as file:
    sensitivity = list(csv.DictReader(file))

metric = 'income_median_equivalised'
summaries = {(x['geography'], x['income_metric'], x['method']): x for x in analysis['summaries']}
groups = analysis['deciles']


def row(geography, method='entrance'):
    return summaries[(geography, metric, method)]


def decile_gap(geography, method='entrance'):
    rows = {x['group']: x for x in groups if x['geography'] == geography and x['income_metric'] == metric and x['method'] == method}
    return rows[10]['mean_score'] - rows[1]['mean_score']


def shares(geography):
    return [x['population_share'] for x in groups if x['geography'] == geography and x['income_metric'] == metric and x['method'] == 'entrance']


def variants(geography, method, subset):
    return [x for x in sensitivity if x['geography'] == geography and x['income_metric'] == metric and x['method'] == method and subset(x['variant'])]


def bounds(rows, field):
    values = [float(x[field]) for x in rows]
    return f'{min(values):.3f}–{max(values):.3f}'


def bounds_percent(rows, field):
    values = [100 * float(x[field]) for x in rows]
    return f'{min(values):.1f}–{max(values):.1f}%'


lines = [
    '# Results and sensitivity',
    '',
    'Generated by `scripts/08_write_results.py` from the saved section and sensitivity tables. These are descriptive associations between **area income** and a constructed rail score; they do not support a causal claim.',
    '',
    '## Main specification',
    '',
    '| Geography | Eligible sections | Section Spearman ρ | Highest minus lowest area-income decile mean score | Actual decile resident shares |',
    '| --- | ---: | ---: | ---: | ---: |',
]
for geography, name in [('region', 'Comunidad de Madrid'), ('city', 'Madrid municipality')]:
    r = row(geography)
    share = shares(geography)
    lines.append(f'| {name} | {r["sections"]:,} | {r["spearman_rho"]:.3f} | {decile_gap(geography):+.3f} | {min(share)*100:.2f}–{max(share)*100:.2f}% |')
lines += [
    '',
    'The main score uses entrances, `D50=600 m`, `p=2.5`, and a `0.10` second-station contribution for the same line. INE median income per consumption unit is the income measure. Six sections with 498 modelled residents have no value for this measure and are excluded from this table.',
    '',
    '## Fixed sensitivity grid',
    '',
    'The nine distance-decay combinations and four duplicate factors were specified before viewing the association. Ranges below cover the nine distance-decay combinations only. Full values, including duplicate-factor variants and all three income measures, are in `validation/generated/sensitivity_summary.csv`.',
    '',
    '| Geography | Origin | Income–score ρ | Score-rank ρ vs main | Decile score gap | Residents changing Four Madrids quadrant |',
    '| --- | --- | ---: | ---: | ---: | ---: |',
]
for geography, name in [('region', 'Comunidad'), ('city', 'Madrid city')]:
    for method in ['entrance', 'platform']:
        v = variants(geography, method, lambda x: x.startswith('d'))
        lines.append(f'| {name} | {method} | {bounds(v,"income_score_spearman")} | {bounds(v,"rank_spearman_vs_main")} | {bounds(v,"top_bottom_decile_gap")} | {bounds_percent(v,"four_madrids_changed_population_share")} |')
lines += [
    '',
    'The platform specification is a representation check using only platforms linked to confirmed boarding lines. Its main-specification section correlations are '+
    f'{row("region","platform")["spearman_rho"]:.3f} (region) and {row("city","platform")["spearman_rho"]:.3f} (city).',
    '',
    '## Reading the maps',
    '',
    'The component score map uses actual component polygons at close zoom. A 2 km population-weighted surface is used at wider zoom for performance and must not be read as another observation unit. Income remains a 2024 census-section attribute.',
    '',
]
(root / 'RESULTS.md').write_text('\n'.join(lines))
print('Wrote RESULTS.md')
